export const LANGUAGES = [
  { code: 'el', label: 'Ελληνικά' },
  { code: 'en', label: 'English' },
]

export function strings(language) {
  return STRINGS[language] || STRINGS.el
}

export function formatMl(ml, language) {
  if (ml >= 1000) return `${(ml / 1000).toLocaleString(language === 'el' ? 'el-GR' : 'en-GB', { maximumFractionDigits: 2 })} L`
  return `${ml} ml`
}
